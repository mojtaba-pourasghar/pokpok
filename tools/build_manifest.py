#!/usr/bin/env python3
"""Writes assets/content/asset_manifest.json: every bundled art and audio file with a stable id,
relative path, content type, version, size and sha256.

The app reads it to resolve art ids; cloudflare/scripts/build_packs.py reads it to build the
downloadable packs, so the checksums the app verifies come from one place.

    python3 tools/build_manifest.py
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUT = ASSETS / "content/asset_manifest.json"
TYPES = {".svg": "image/svg+xml", ".webp": "image/webp", ".png": "image/png", ".mp3": "audio/mpeg", ".ogg": "audio/ogg"}
SIZE = re.compile(r'viewBox="0 0 (\d+) (\d+)"')
VERSION = 1


def main() -> None:
    entries = []
    for top in ("art", "audio"):
        for f in sorted((ASSETS / top).rglob("*")):
            if not f.is_file() or f.suffix not in TYPES:
                continue
            rel = f.relative_to(ASSETS).as_posix()
            data = f.read_bytes()
            e = {
                "id": f.stem if top == "art" else rel[len("audio/"):].rsplit(".", 1)[0],
                "group": f.parent.relative_to(ASSETS / top).as_posix(),
                "path": rel,
                "type": TYPES[f.suffix],
                "version": VERSION,
                "bytes": len(data),
                "sha256": hashlib.sha256(data).hexdigest(),
            }
            if f.suffix == ".svg":
                m = SIZE.search(data[:300].decode("utf-8", "ignore"))
                if m:
                    e["width"], e["height"] = int(m.group(1)), int(m.group(2))
            entries.append(e)
    OUT.write_text(json.dumps({
        "version": VERSION,
        "note": "Generated by tools/build_manifest.py — do not edit by hand.",
        "assets": entries,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(entries)} assets → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
