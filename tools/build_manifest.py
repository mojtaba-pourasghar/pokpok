#!/usr/bin/env python3
"""Writes assets/content/asset_manifest.json: every bundled audio file with a stable id, relative
path, content type, version, size and sha256 (pictures are cartoons drawn in code, lib/ui/toons).

The content test checks it against the bundle, so a changed sound without a refreshed manifest
fails CI.

    python3 tools/build_manifest.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUT = ASSETS / "content/asset_manifest.json"
TYPES = {".mp3": "audio/mpeg", ".ogg": "audio/ogg"}
VERSION = 1


def main() -> None:
    entries = []
    for f in sorted((ASSETS / "audio").rglob("*")):
        if not f.is_file() or f.suffix not in TYPES:
            continue
        rel = f.relative_to(ASSETS).as_posix()
        data = f.read_bytes()
        entries.append({
            "id": rel[len("audio/"):].rsplit(".", 1)[0],
            "group": f.parent.relative_to(ASSETS / "audio").as_posix(),
            "path": rel,
            "type": TYPES[f.suffix],
            "version": VERSION,
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        })
    OUT.write_text(json.dumps({
        "version": VERSION,
        "note": "Generated by tools/build_manifest.py — do not edit by hand.",
        "assets": entries,
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(entries)} assets → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
